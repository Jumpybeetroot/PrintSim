"""Generate a compact symbol & line-range index (docs/CODEBASE_MAP.md) for fast navigation.

Run:
    uv run python scripts/gen_codebase_map.py
"""

from __future__ import annotations

import ast
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
OUT_PATH = ROOT / "docs" / "CODEBASE_MAP.md"


def _index_python_file(path: Path) -> tuple[int, list[str]]:
    text = path.read_text(encoding="utf-8", errors="replace")
    lines = text.splitlines()
    entries: list[str] = []
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return len(lines), entries

    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if node.name.startswith("_") and len(lines) < 500:
                continue
            end = getattr(node, "end_lineno", node.lineno)
            entries.append(f"`{node.name}()` L{node.lineno}–{end}")
        elif isinstance(node, ast.ClassDef):
            end = getattr(node, "end_lineno", node.lineno)
            methods = [
                n.name
                for n in node.body
                if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
                and not n.name.startswith("_")
            ][:6]
            ms = f" [{', '.join(methods)}]" if methods else ""
            entries.append(f"`class {node.name}` L{node.lineno}–{end}{ms}")
    return len(lines), entries


_TS_DEF_RE = re.compile(
    r"^(?:export\s+)?(?:default\s+)?(?:async\s+)?(?:function|const|class|interface|type)\s+([A-Za-z_][A-Za-z0-9_]*)"
)


def _index_ts_file(path: Path) -> tuple[int, list[str]]:
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    entries: list[str] = []
    for i, line in enumerate(lines, start=1):
        m = _TS_DEF_RE.match(line)
        if m:
            name = m.group(1)
            if name.startswith("_") and len(lines) < 500:
                continue
            entries.append(f"`{name}` L{i}")
    return len(lines), entries[:24]


def _index_css_sections(path: Path) -> tuple[int, list[str]]:
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    entries: list[str] = []
    for i, line in enumerate(lines, start=1):
        s = line.strip()
        if s.startswith("/*") and ("===" in s or "---" in s or len(s) > 12 and s.endswith("*/")):
            label = s.strip("/*-= \t")
            if label and len(label) < 64:
                entries.append(f"{label} (L{i})")
    return len(lines), entries[:20]


def generate_map() -> str:
    parts: list[str] = [
        "# PrintSim Codebase Map",
        "",
        "> Auto-generated by `uv run python scripts/gen_codebase_map.py`. Read this index first to jump straight to target line ranges (`StartLine`/`EndLine`) instead of reading whole large files.",
        "",
        "## Backend (`src/printsim/`)",
        "",
    ]

    for py_path in sorted((ROOT / "src" / "printsim").rglob("*.py")):
        if "__pycache__" in py_path.parts or py_path.name == "__init__.py":
            continue
        rel = py_path.relative_to(ROOT).as_posix()
        nlines, syms = _index_python_file(py_path)
        shown = syms[:14]
        more = f" *(+{len(syms) - len(shown)} more)*" if len(syms) > len(shown) else ""
        sym_str = ", ".join(shown) + more if shown else "*(constants/helpers)*"
        parts.append(f"- **`{rel}`** ({nlines} lines): {sym_str}")

    parts.extend(["", "## Scripts (`scripts/`)", ""])
    for py_path in sorted((ROOT / "scripts").glob("*.py")):
        rel = py_path.relative_to(ROOT).as_posix()
        nlines, syms = _index_python_file(py_path)
        shown = syms[:10]
        parts.append(f"- **`{rel}`** ({nlines} lines): {', '.join(shown) if shown else 'CLI script'}")

    parts.extend(["", "## Web 3D Studio (`web/src/`)", ""])
    for ts_path in sorted((ROOT / "web" / "src").rglob("*")):
        if not ts_path.is_file() or ts_path.suffix not in {".ts", ".tsx", ".css"}:
            continue
        rel = ts_path.relative_to(ROOT).as_posix()
        if ts_path.suffix == ".css":
            nlines, syms = _index_css_sections(ts_path)
        else:
            nlines, syms = _index_ts_file(ts_path)
        shown = syms[:12]
        more = f" *(+{len(syms) - len(shown)} more)*" if len(syms) > len(shown) else ""
        parts.append(f"- **`{rel}`** ({nlines} lines): {', '.join(shown) + more if shown else 'module'}")

    parts.append("")
    return "\n".join(parts)


def main() -> None:
    content = generate_map()
    OUT_PATH.write_text(content, encoding="utf-8")
    print(f"Wrote {OUT_PATH.relative_to(ROOT)} ({len(content.splitlines())} lines)")


if __name__ == "__main__":
    main()
