def get_cord_micromechanics_spec(profile_family: str, core: str = "fiberglass") -> CordMicromechanicsSpec:
    """Resolve the physical cord micromechanics specification for a belt profile and core."""
    pk = _resolve_profile_key(profile_family, core=core)
    c = str(core).strip().lower()
    if (pk, c) in CORD_MICROMECHANICS_CATALOG:
        return CORD_MICROMECHANICS_CATALOG[(pk, c)]
    if c == "steel":
        return CORD_MICROMECHANICS_CATALOG[("at3", "steel")]
    if c == "aramid":
        return CORD_MICROMECHANICS_CATALOG[("2gt", "aramid")]
    return CORD_MICROMECHANICS_CATALOG[("2gt", "fiberglass")]


def _costello_parameters(
    *,
    n_cords: float,
    filament_modulus_pa: float,
    filament_area_m2: float,
    helix_angle_rad: float,
    helix_radius_m: float,
    matrix_modulus_pa: float,
    core_transverse_stiffness_pa: float,
    matrix_confinement_factor: float,
    radial_compaction_clearance_m: float,
) -> tuple[float, float, float]:
    """Compute Costello asymptotic ceiling EA_inf (N), zero-tension compliance ratio beta_0,
    and exponential compaction rate lambda_comp (1/N).

    All three quantities are strictly finite and singularity-free down to alpha = 0 (straight cord).
    """
    n_c = float(n_cords)
    e_f = float(filament_modulus_pa)
    a_f = float(filament_area_m2)
    alpha = float(helix_angle_rad)
    r_0 = float(helix_radius_m)
    e_m = max(float(matrix_modulus_pa), 0.0)
    k_core = float(core_transverse_stiffness_pa)
    c_m = max(float(matrix_confinement_factor), 0.0)
    delta_g = float(radial_compaction_clearance_m)

    if n_c <= 0.0 or e_f <= 0.0 or a_f <= 0.0:
        raise ValueError("n_cords, filament_modulus_pa, and filament_area_m2 must be positive")
    if not (0.0 <= alpha < 0.5 * math.pi):
        raise ValueError(f"helix_angle_rad must be in [0, pi/2), got {alpha}")
    if r_0 <= 0.0 or delta_g <= 0.0:
        raise ValueError("helix_radius_m and radial_compaction_clearance_m must be positive")

    k_r0 = k_core + c_m * e_m
    if k_r0 <= 0.0:
        raise ValueError("Effective radial confinement stiffness k_r0 must be positive")

    ca = math.cos(alpha)
    sa = math.sin(alpha)
    ta = sa / ca

    ea_inf = n_c * e_f * a_f * (ca**3)
    beta_0 = (e_f * a_f * (sa**4)) / (k_r0 * (r_0**2))
    # Exponential compaction rate lambda_comp = (tan(alpha) * sin(alpha)) / (N_c * k_r0 * r_0 * delta_g)
    lam_comp = (ta * sa) / (n_c * k_r0 * r_0 * delta_g)
    return ea_inf, beta_0, lam_comp


def cord_crimp_tangent_ea_n(
    tension_n: float,
    *,
    n_cords: float,
    filament_modulus_pa: float,
    filament_area_m2: float,
    helix_angle_rad: float,
    helix_radius_m: float = 1.10e-4,
    matrix_modulus_pa: float = 12.0e6,
    core_transverse_stiffness_pa: float = 1.95e9,
    matrix_confinement_factor: float = 14.0,
    radial_compaction_clearance_m: float = 5.8e-7,
) -> float:
    """Costello helical-cord tangent axial stiffness EA_tan(T) (N).

    Derives the low-tension straightening toe from helical radial contraction against the
    transverse fiber/RFL core and elastomeric matrix radial confinement, saturating
    asymptotically at the exact locked-radius Costello upper bound:

        EA_inf = N_cords * E_f * A_f * cos^3(alpha)

    Closed-form tangent modulus:

        EA_tan(T) = EA_inf / (1 + beta_0 * exp(-lambda_comp * max(T, 0)))

    where:
      - ``beta_0 = E_f * A_f * sin^4(alpha) / (k_r0 * r_0^2)``
      - ``k_r0 = k_r_core + c_m * E_matrix``
      - ``lambda_comp = tan(alpha) * sin(alpha) / (N_cords * k_r0 * r_0 * delta_g)``
    """
    ea_inf, beta_0, lam_comp = _costello_parameters(
        n_cords=n_cords,
        filament_modulus_pa=filament_modulus_pa,
        filament_area_m2=filament_area_m2,
        helix_angle_rad=helix_angle_rad,
        helix_radius_m=helix_radius_m,
        matrix_modulus_pa=matrix_modulus_pa,
        core_transverse_stiffness_pa=core_transverse_stiffness_pa,
        matrix_confinement_factor=matrix_confinement_factor,
        radial_compaction_clearance_m=radial_compaction_clearance_m,
    )
    t_pos = max(float(tension_n), 0.0)
    arg = min(lam_comp * t_pos, 700.0)
    return float(ea_inf / (1.0 + beta_0 * math.exp(-arg)))


def cord_crimp_secant_ea_n(
    tension_n: float,
    *,
    n_cords: float,
    filament_modulus_pa: float,
    filament_area_m2: float,
    helix_angle_rad: float,
    helix_radius_m: float = 1.10e-4,
    matrix_modulus_pa: float = 12.0e6,
    core_transverse_stiffness_pa: float = 1.95e9,
    matrix_confinement_factor: float = 14.0,
    radial_compaction_clearance_m: float = 5.8e-7,
) -> float:
    """Exact integrated Costello secant axial stiffness T / epsilon_z(T) (N).

    Integrates ``d(eps_z)/dT = 1 / EA_tan(T)`` in closed form from 0 to ``tension_n``:

        eps_z(T) = (T / EA_inf) * [1 + beta_0 * (1 - exp(-lambda * T)) / (lambda * T)]
    """
    ea_inf, beta_0, lam_comp = _costello_parameters(
        n_cords=n_cords,
        filament_modulus_pa=filament_modulus_pa,
        filament_area_m2=filament_area_m2,
        helix_angle_rad=helix_angle_rad,
        helix_radius_m=helix_radius_m,
        matrix_modulus_pa=matrix_modulus_pa,
        core_transverse_stiffness_pa=core_transverse_stiffness_pa,
        matrix_confinement_factor=matrix_confinement_factor,
        radial_compaction_clearance_m=radial_compaction_clearance_m,
    )
    t_pos = max(float(tension_n), 0.0)
    x = lam_comp * t_pos
    if x < 1e-9:
        phi = 1.0 - 0.5 * x + (x * x) / 6.0
    else:
        phi = (1.0 - math.exp(-min(x, 700.0))) / x
    return float(ea_inf / (1.0 + beta_0 * phi))


def cord_crimp_factor_micromechanics(
    tension_n: float,
    *,
    profile_family: str = "2gt",
    width_mm: float = 6.0,
    core: str = "fiberglass",
    matrix_modulus_retention: float = 1.0,
    elastomer_modulus_scale: float = 1.0,
) -> float:
    """Dimensionless Costello tangent crimp-straightening ratio EA_tan(T) / EA_inf in (0, 1]."""
    cspec = get_cord_micromechanics_spec(profile_family, core=core)
    n_c = cspec.n_cords_for_width(width_mm)
    e_m = cspec.e_matrix_25c_pa * max(float(matrix_modulus_retention), 0.05) * max(float(elastomer_modulus_scale), 0.1)
    ea_tan = cord_crimp_tangent_ea_n(
        tension_n,
        n_cords=n_c,
        filament_modulus_pa=cspec.filament_modulus_pa,
        filament_area_m2=cspec.filament_area_m2,
        helix_angle_rad=cspec.helix_angle_rad,
        helix_radius_m=cspec.helix_radius_m,
        matrix_modulus_pa=e_m,
        core_transverse_stiffness_pa=cspec.core_transverse_stiffness_pa,
        matrix_confinement_factor=cspec.matrix_confinement_factor,
        radial_compaction_clearance_m=cspec.radial_compaction_clearance_m,
    )
    ea_inf = n_c * cspec.filament_modulus_pa * cspec.filament_area_m2 * (math.cos(cspec.helix_angle_rad) ** 3)
    return float(ea_tan / ea_inf)


def belt_cord_tangent_ea_n(
    profile_family: str,
    width_mm: float,
    tension_n: float,
    *,
    core: str = "fiberglass",
    matrix_modulus_retention: float = 1.0,
    elastomer_modulus_scale: float = 1.0,
) -> float:
    """Convenience wrapper returning Costello tangent EA (N) for a catalog belt specification."""
    cspec = get_cord_micromechanics_spec(profile_family, core=core)
    n_c = cspec.n_cords_for_width(width_mm)
    e_m = cspec.e_matrix_25c_pa * max(float(matrix_modulus_retention), 0.05) * max(float(elastomer_modulus_scale), 0.1)
    return cord_crimp_tangent_ea_n(
        tension_n,
        n_cords=n_c,
        filament_modulus_pa=cspec.filament_modulus_pa,
        filament_area_m2=cspec.filament_area_m2,
        helix_angle_rad=cspec.helix_angle_rad,
        helix_radius_m=cspec.helix_radius_m,
        matrix_modulus_pa=e_m,
        core_transverse_stiffness_pa=cspec.core_transverse_stiffness_pa,
        matrix_confinement_factor=cspec.matrix_confinement_factor,
        radial_compaction_clearance_m=cspec.radial_compaction_clearance_m,
    )


