def pitch_cell_tooth_mesh_k(
    profile_family: str,
    line_tension_n_per_mm: float,
    *,
    matrix_modulus_retention: float = 1.0,
    elastomer_seating_factor: float = 1.0,
    pulley_teeth: int = 20,
    pitch_mm: float | None = None,
    core: str | None = None,
    calibration: dict[str, PitchCellFEACalibration] | None = None,
) -> float:
    """First-principles single-tooth shear stiffness k_t (N/(m*mm)) backed by 3D Tet10 FEA.

    Includes:
      - Active-set radial flank & root-land seating vs. line tension ``q0 = T0 / width_mm``,
        scaled by radial wrap pressure ratio ``Z_ref / Z_pulley`` (since ``p_r = 2*pi*q0 / (Z*p)``).
      - Linear scaling with elastomer matrix thermal modulus retention ``E_matrix(T) / E_matrix(25 C)``.
      - Optional compound seating modifier (e.g. softer GT3 base elastomer).
    """
    table = _EMBEDDED_PITCH_CELL_CALIBRATION if calibration is None else calibration
    key = _resolve_profile_key(profile_family, pitch_mm=pitch_mm, core=core)
    cal = table[key]

    q0 = max(float(line_tension_n_per_mm), 0.0)
    ret = max(float(matrix_modulus_retention), 0.05)
    e_seat = max(float(elastomer_seating_factor), 0.1)

    # Radial wrap pressure p_r = q0 / R = 2*pi*q0 / (Z*p); scale q0 relative to nominal Z_ref
    z_eff = max(float(pulley_teeth), 10.0)
    q_eff = q0 * (float(cal.nominal_pulley_teeth) / z_eff)

    s0 = cal.seating_floor_s0
    q_s = max(cal.seating_scale_q_n_per_mm, 1e-6)
    seating_ratio = s0 + (1.0 - s0) * (1.0 - math.exp(-min(q_eff / q_s, 700.0)))

    # Mild geometric aspect adjustment for non-calibrated 5 mm pitch (AT5) or HTD3M profiles
    pf_l = str(profile_family).strip().lower()
    geom_mult = 1.0
    if pf_l == "at5" or (pitch_mm is not None and pitch_mm >= 4.5):
        geom_mult = 1.15
    elif pf_l == "htd3m":
        geom_mult = 0.88
    elif pf_l == "at3_gen3":
        geom_mult = 1.10

    return float(cal.k_t_full_n_per_m_mm * geom_mult * ret * e_seat * seating_ratio)


def pitch_cell_gerbert_mesh_stiffness_n_m(
    profile_family: str,
    width_mm: float,
    tension_n: float,
    ea_eff_n: float,
    *,
    pitch_mm: float | None = None,
    pulley_teeth: int = 20,
    wrap_angle_deg: float = 180.0,
    matrix_modulus_retention: float = 1.0,
    elastomer_seating_factor: float = 1.0,
    core: str | None = None,
    calibration: dict[str, PitchCellFEACalibration] | None = None,
) -> float:
    """Engaged pulley tooth-mesh stiffness (N/m) combining Tet10 pitch-cell k_t with Gerbert's chain."""
    table = _EMBEDDED_PITCH_CELL_CALIBRATION if calibration is None else calibration
    key = _resolve_profile_key(profile_family, pitch_mm=pitch_mm, core=core)
    cal = table[key]

    w_mm = max(float(width_mm), 1.0)
    q0 = max(float(tension_n), 0.0) / w_mm
    k_t = pitch_cell_tooth_mesh_k(
        profile_family,
        q0,
        matrix_modulus_retention=matrix_modulus_retention,
        elastomer_seating_factor=elastomer_seating_factor,
        pulley_teeth=pulley_teeth,
        pitch_mm=pitch_mm,
        core=core,
        calibration=table,
    )
    p_m = (float(pitch_mm) if pitch_mm is not None else cal.pitch_mm) * 1e-3
    z_e = max(float(pulley_teeth) * (float(wrap_angle_deg) / 360.0), 1.0)
    ea_safe = max(float(ea_eff_n), 100.0)
    lam = math.acosh(1.0 + (k_t * w_mm * p_m) / (2.0 * ea_safe))
    return float(k_t * w_mm * math.tanh(lam * z_e) / max(math.tanh(lam), 1e-9))


def pitch_cell_bending_energy_fractions(
    profile_family: str,
    *,
    matrix_modulus_retention: float = 1.0,
    pitch_mm: float | None = None,
    core: str | None = None,
    calibration: dict[str, PitchCellFEACalibration] | None = None,
) -> tuple[float, float]:
    """Return (cord_bending_fraction, elastomer_bending_fraction) vs matrix modulus retention."""
    table = _EMBEDDED_PITCH_CELL_CALIBRATION if calibration is None else calibration
    key = _resolve_profile_key(profile_family, pitch_mm=pitch_mm, core=core)
    cal = table[key]

    ret = max(float(matrix_modulus_retention), 0.05)
    # Partition total EI into matrix-sensitive component (m_s * ret) and cord-dominated component (1 - m_s)
    m_s = cal.ei_matrix_retention_slope
    c_part = max(1.0 - m_s, 0.05)
    m_part = m_s * ret
    tot = c_part + m_part
    f_cord = c_part / tot
    return float(f_cord), float(1.0 - f_cord)


def pitch_cell_flexural_rigidity_nm2(
    profile_family: str,
    width_mm: float,
    *,
    matrix_modulus_retention: float = 1.0,
    core: str | None = None,
    pitch_mm: float | None = None,
    calibration: dict[str, PitchCellFEACalibration] | None = None,
) -> float:
    """First-principles composite belt flexural rigidity EI_b (N*m^2) backed by 3D Tet10 ABD FEA.

    Accounts for:
      - Exact 3D backing + tooth-root shear-lag + embedded stranded-cord bending from Tet10 FEA.
      - Thermal matrix elastomer softening via the FEA-calibrated retention slope ``ei_matrix_retention_slope``.
      - Cord material substitution (e.g., aramid or steel cords in a 2GT/3GT profile) applied strictly
        to the cord bending fraction rather than rescaling the elastomer backing.
    """
    table = _EMBEDDED_PITCH_CELL_CALIBRATION if calibration is None else calibration
    key = _resolve_profile_key(profile_family, pitch_mm=pitch_mm, core=core)
    cal = table[key]

    w_m = max(float(width_mm), 1.0) * 1e-3
    ret = max(float(matrix_modulus_retention), 0.05)

    # Split baseline 25 C EI_per_m into cord-dominated and matrix-sensitive parts from Tet10 FEA
    m_s = cal.ei_matrix_retention_slope
    ei_cord_base = cal.ei_25c_nm2_per_m * (1.0 - m_s)
    ei_elast_base = cal.ei_25c_nm2_per_m * m_s

    # Apply cord material adjustment strictly to the cord bending component when overriding default_core
    c_req = cal.default_core if core is None else str(core).strip().lower()
    if c_req != cal.default_core:
        # Relative stranded-cord flexural rigidity (aramid finer low-compression filaments ~0.80x glass;
        # stranded steel wires ~2.6x glass due to larger wire radius r_w^4 and E_steel = 205 GPa)
        cord_bend_rel = {"fiberglass": 1.0, "aramid": 0.80, "steel": 2.60}
        ratio = cord_bend_rel.get(c_req, 1.0) / cord_bend_rel.get(cal.default_core, 1.0)
        ei_cord_base *= ratio

    # Geometric scaling for 5 mm pitch AT5 belts (H_AT5 = 2.7 mm vs H_AT3 = 1.9 mm)
    pf_l = str(profile_family).strip().lower()
    geom_mult = 1.0
    if pf_l == "at5" or (pitch_mm is not None and pitch_mm >= 4.5):
        geom_mult = 2.0

    ei_per_m = geom_mult * (ei_cord_base + ei_elast_base * ret)
    return float(ei_per_m * w_m)


