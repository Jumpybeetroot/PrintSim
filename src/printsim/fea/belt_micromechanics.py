def load_pitch_cell_fea_calibration(
    json_path: str | Path | None = None,
) -> dict[str, PitchCellFEACalibration]:
    """Load calibrated 3D Tet10 pitch-cell constants from JSON if available, else embedded table."""
    if json_path is None:
        return dict(_EMBEDDED_PITCH_CELL_CALIBRATION)
    path = Path(json_path)
    if not path.is_file():
        return dict(_EMBEDDED_PITCH_CELL_CALIBRATION)
    raw = json.loads(path.read_text(encoding="utf-8"))
    out: dict[str, PitchCellFEACalibration] = dict(_EMBEDDED_PITCH_CELL_CALIBRATION)
    for pid, entry in raw.get("profiles", {}).items():
        spec = entry["spec"]
        cal = entry["calibrated_summary"]
        out[str(pid).lower()] = PitchCellFEACalibration(
            profile_family=str(pid).lower(),
            pitch_mm=float(spec["pitch_mm"]),
            total_height_mm=float(spec["total_height_mm"]),
            tooth_height_mm=float(spec["tooth_height_mm"]),
            default_core=str(spec["cord_material"]),
            matrix_material=str(spec["matrix_material"]),
            e_matrix_25c_pa=float(spec["e_matrix_25c_pa"]),
            nominal_pulley_teeth=int(spec["nominal_pulley_teeth"]),
            k_t_full_n_per_m_mm=float(cal["k_t_full_n_per_m_mm"]),
            seating_floor_s0=float(cal["seating_floor_s0"]),
            seating_scale_q_n_per_mm=float(cal["seating_scale_q_n_per_mm"]),
            ei_25c_nm2_per_m=float(cal["ei_25c_nm2_per_m"]),
            cord_bending_fraction_25c=float(cal["cord_bending_fraction_25c"]),
            elastomer_bending_fraction_25c=float(cal["elastomer_bending_fraction_25c"]),
            ei_matrix_retention_slope=float(cal["ei_matrix_retention_slope"]),
        )
    return out


def _resolve_profile_key(profile_family: str, pitch_mm: float | None = None, core: str | None = None) -> str:
    """Normalize PrintSim profile_family strings onto calibrated FEA keys (2gt, 3gt, at3)."""
    pf = str(profile_family).strip().lower()
    if pf in ("2gt", "2mgt", "gt2", "gt3"):
        return "2gt"
    if pf in ("3gt", "3mgt"):
        return "3gt"
    if pf in ("at3", "at3_gen3", "htd3m", "at5"):
        return "at3"
    if pitch_mm is not None:
        if pitch_mm < 2.5:
            return "2gt"
        if core == "steel":
            return "at3"
        return "3gt"
    return "2gt"


