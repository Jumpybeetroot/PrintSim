"""First-principles belt micromechanics and 3D pitch-cell Tet10 FEA surrogate models.

Provides fast, Pyodide-WASM-safe pure-Python/NumPy physics models calibrated against the
3D single-pitch-cell Tet10 continuum FEA dataset (``data/touchstones/belt_pitch_cell_fea.json``,
generated by ``scripts/calibrate_belt_pitch_cell_fea.py``):

1. **Costello helical-cord micromechanics** (``cord_crimp_tangent_ea_n``, ``cord_crimp_secant_ea_n``,
   ``cord_crimp_factor_micromechanics``):
   Derives the low-tension straightening toe of multi-filament twisted/stranded tensile cords
   from cord count ``N_cords``, filament modulus ``E_f``, filament cross-sectional area ``A_f``,
   helix lay angle ``alpha``, transverse core/matrix radial confinement ``k_r0``, and radial
   compaction clearance ``delta_g``, saturating monotonically and asymptotically at the exact
   Costello locked-radius ceiling ``N_cords * E_f * A_f * cos^3(alpha)``.
2. **Tooth-mesh shear stiffness & radial seating** (``pitch_cell_tooth_mesh_k``,
   ``pitch_cell_gerbert_mesh_stiffness_n_m``):
   Backed by 3D Tet10 active-set unilateral pulley-groove seating FEA for ``2GT``, ``3GT``,
   and ``AT3`` profiles, accounting for line tension ``q0 = T0 / width_mm``, pulley radius wrap
   pressure scaling ``20 / pulley_teeth``, and thermal elastomer modulus retention ``E_matrix(T)``.
3. **Composite flexural rigidity & energy partition** (``pitch_cell_flexural_rigidity_nm2``,
   ``pitch_cell_bending_energy_fractions``):
   Backed by exact 3D Tet10 2x2 ABD static-condensation bending FEA across matrix modulus
   retention ``r_m = E_matrix(T) / E_matrix(25 C)``.

Pyodide WASM safety:
  This module imports ONLY Python stdlib (``dataclasses``, ``json``, ``math``, ``pathlib``,
  ``typing``). It MUST NOT import ``build123d``, ``gmsh``, ``skfem``, or heavy ``scipy.*``
  subpackages at module top level.
"""

